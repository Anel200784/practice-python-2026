# 1. Тізім туралы түсінік және оны шығару
numbers = [10, 20, 30, 40, 50]
print("Толық тізім:", numbers)

# 2. Тізім элементтеріне индекс арқылы қол жеткізу
print("Бірінші элемент (индекс 0):", numbers[0])
print("Екінші элемент (индекс 1):", numbers[1])

# 3. Тізімге жаңа элемент қосу (append)
simple_list = [1, 2, 3]
simple_list.append(4)
print("Элемент қосылғаннан кейінгі тізім:", simple_list)

# 4. Тізімнің ұзындығын (элемент санын) анықтау
length_list = [5, 10, 15]
print("Тізімнің ұзындығы:", len(length_list))

# 5. Цикл арқылы элементтерді жеке-жеке шығару
loop_list = [2, 4, 6, 8]
print("Циклмен шығару:")
for num in loop_list:
    print(num)

# 6. Элементтердің қосындысын циклмен табу
sum_list = [1, 2, 3, 4]
total = 0
for num in sum_list:
    total += num
print("Циклмен табылған қосынды:", total)